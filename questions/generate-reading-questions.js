#!/usr/bin/env node
/**
 * Generate Reading Questions for Grades 2-5
 * This script generates reading questions and updates the comprehensive question banks
 */

const fs = require('fs');
const path = require('path');

// Load the base QuestionGenerator class
const { QuestionGenerator } = require('./question-generator.js');

// Load Reading Generators for Grades 2-5
const {
  Grade2ReadingGenerator,
  Grade3ReadingGenerator,
  Grade4ReadingGenerator,
  Grade5ReadingGenerator
} = require('./reading-generator-grades-2-5.js');

// ============================================================
// UPDATE COMPREHENSIVE QUESTION BANK FILE
// ============================================================

function updateComprehensiveFile(grade, readingQuestions) {
  const gradeKey = grade === 0 ? 'K' : grade;
  const filename = `grade-${gradeKey}-comprehensive.js`;
  const filepath = path.join(__dirname, filename);

  console.log(`\n📝 Updating ${filename}...`);

  // Read existing file
  let content = fs.readFileSync(filepath, 'utf8');

  // Extract the variable name
  const varMatch = content.match(/const\s+(\w+)\s*=\s*{/);
  if (!varMatch) {
    console.error(`❌ Could not find variable declaration in ${filename}`);
    return;
  }
  const varName = varMatch[1];

  // Parse the existing data structure
  const dataMatch = content.match(/const\s+\w+\s*=\s*({[\s\S]*});/);
  if (!dataMatch) {
    console.error(`❌ Could not parse data structure in ${filename}`);
    return;
  }

  // Use eval to get the object (safe in this context as we control the file)
  let bankData;
  try {
    eval('bankData = ' + dataMatch[1]);
  } catch (e) {
    console.error(`❌ Error parsing ${filename}:`, e.message);
    return;
  }

  // Update reading array
  const oldCount = bankData.reading ? bankData.reading.length : 0;
  bankData.reading = readingQuestions;
  const newCount = bankData.reading.length;

  console.log(`  ✅ Reading questions: ${oldCount} → ${newCount}`);

  // Calculate total questions
  const totalQuestions = Object.values(bankData).reduce((sum, arr) =>
    Array.isArray(arr) ? sum + arr.length : sum, 0
  );

  // Generate new file content
  const header = `/**
 * Learning Spectrum - Grade ${gradeKey} Comprehensive Question Bank
 * Auto-generated by generate-all-questions.js
 * Total Questions: ${totalQuestions}
 */

const ${varName} = ${JSON.stringify(bankData, null, 2)};

if (typeof module !== 'undefined' && module.exports) {
  module.exports = ${varName};
}

if (typeof window !== 'undefined') {
  window.${varName} = ${varName};
}
`;

  // Write back to file
  fs.writeFileSync(filepath, header, 'utf8');
  console.log(`  ✅ File updated successfully!`);
  console.log(`  📊 Total questions in file: ${totalQuestions}`);
}

// ============================================================
// MAIN EXECUTION
// ============================================================

console.log('🚀 Generating Reading Questions for Grades 2-5\n');
console.log('='.repeat(60));

// Grade 2
console.log('\n📚 Grade 2 Reading Questions');
console.log('-'.repeat(60));
const grade2Gen = new Grade2ReadingGenerator();
const grade2Reading = grade2Gen.generateAll();
console.log(`Generated ${grade2Reading.length} Grade 2 reading questions`);
updateComprehensiveFile(2, grade2Reading);

// Grade 3
console.log('\n📚 Grade 3 Reading Questions');
console.log('-'.repeat(60));
const grade3Gen = new Grade3ReadingGenerator();
const grade3Reading = grade3Gen.generateAll();
console.log(`Generated ${grade3Reading.length} Grade 3 reading questions`);
updateComprehensiveFile(3, grade3Reading);

// Grade 4
console.log('\n📚 Grade 4 Reading Questions');
console.log('-'.repeat(60));
const grade4Gen = new Grade4ReadingGenerator();
const grade4Reading = grade4Gen.generateAll();
console.log(`Generated ${grade4Reading.length} Grade 4 reading questions`);
updateComprehensiveFile(4, grade4Reading);

// Grade 5
console.log('\n📚 Grade 5 Reading Questions');
console.log('-'.repeat(60));
const grade5Gen = new Grade5ReadingGenerator();
const grade5Reading = grade5Gen.generateAll();
console.log(`Generated ${grade5Reading.length} Grade 5 reading questions`);
updateComprehensiveFile(5, grade5Reading);

console.log('\n' + '='.repeat(60));
console.log('✅ All reading questions generated successfully!\n');

// Summary
console.log('📊 Summary:');
console.log(`  Grade 2: ${grade2Reading.length} questions`);
console.log(`  Grade 3: ${grade3Reading.length} questions`);
console.log(`  Grade 4: ${grade4Reading.length} questions`);
console.log(`  Grade 5: ${grade5Reading.length} questions`);
console.log(`  Total: ${grade2Reading.length + grade3Reading.length + grade4Reading.length + grade5Reading.length} reading questions\n`);
